import { NextRequest, NextResponse } from "next/server";
import DbConnect from "@/app/libs/dbConnect";
import Barcode, { Department } from "@/app/libs/models/barcode";

// POST - Generate outpass for a barcode
export async function POST(request: NextRequest) {
  try {
    await DbConnect();

    const body = await request.json();
    const { barcodeData, department, scannedBy } = body;

    if (!barcodeData) {
      return NextResponse.json(
        { success: false, message: "Barcode data is required" },
        { status: 400 }
      );
    }

    if (!department) {
      return NextResponse.json(
        { success: false, message: "Department is required" },
        { status: 400 }
      );
    }

    // Store department cannot generate outpass
    if (department === "Store") {
      return NextResponse.json(
        { success: false, message: "Store department cannot generate outpass" },
        { status: 403 }
      );
    }

    if (!scannedBy) {
      return NextResponse.json(
        { success: false, message: "Worker name is required" },
        { status: 400 }
      );
    }

    // Parse barcode data
    let parsedData;
    try {
      parsedData = JSON.parse(barcodeData);
    } catch {
      return NextResponse.json(
        { success: false, message: "Invalid barcode format" },
        { status: 400 }
      );
    }

    // Find the barcode
    const barcode = await Barcode.findOne({ barcodeData });

    if (!barcode) {
      return NextResponse.json(
        { success: false, message: "Barcode not found" },
        { status: 404 }
      );
    }

    // Check if already on outpass
    if (barcode.currentDepartment === "Outpass") {
      return NextResponse.json(
        { success: false, message: "This item is already on Outpass", alreadyOnOutpass: true },
        { status: 400 }
      );
    }

    // Check if defective or damaged
    if (barcode.status === "defective" || barcode.status === "damaged") {
      return NextResponse.json(
        { success: false, message: "Cannot generate outpass for defective/damaged items" },
        { status: 400 }
      );
    }

    // Update barcode with outpass info
    barcode.departmentHistory.push({
      department: "Outpass" as Department,
      scannedAt: new Date(),
      scannedBy: scannedBy,
    });
    barcode.currentDepartment = "Outpass";
    barcode.scannedAt = new Date();

    await barcode.save();

    return NextResponse.json({
      success: true,
      message: `Outpass generated by ${scannedBy} from ${department}`,
      barcode: {
        id: barcode._id,
        design: barcode.design,
        size: barcode.size,
        suitType: barcode.suitType,
        item: barcode.item,
        unitNumber: barcode.unitNumber,
        status: barcode.status,
        currentDepartment: barcode.currentDepartment,
        departmentHistory: barcode.departmentHistory,
      },
    });
  } catch (error: any) {
    console.error("Outpass error:", error);
    return NextResponse.json(
      { success: false, message: error.message || "Failed to generate outpass" },
      { status: 500 }
    );
  }
}

// GET - Get all items currently on outpass
export async function GET(request: NextRequest) {
  try {
    await DbConnect();

    const { searchParams } = new URL(request.url);
    const design = searchParams.get("design");

    // Build query for items where currentDepartment is Outpass
    const query: any = {
      currentDepartment: "Outpass",
      status: { $nin: ["defective", "damaged"] },
    };

    if (design) {
      query.design = { $regex: design, $options: "i" };
    }

    const outpassItems = await Barcode.find(query)
      .sort({ scannedAt: -1 })
      .lean();

    // Get the outpass info from the last department history entry
    const itemsWithOutpassInfo = outpassItems.map((item: any) => {
      const lastScan = item.departmentHistory[item.departmentHistory.length - 1];
      const previousDept = item.departmentHistory.length > 1 
        ? item.departmentHistory[item.departmentHistory.length - 2] 
        : null;

      return {
        id: item._id,
        design: item.design,
        size: item.size,
        suitType: item.suitType,
        item: item.item,
        unitNumber: item.unitNumber,
        status: item.status,
        outpassInfo: {
          generatedAt: lastScan?.scannedAt,
          generatedBy: lastScan?.scannedBy,
          fromDepartment: previousDept?.department || "Unknown",
        },
        departmentHistory: item.departmentHistory,
      };
    });

    // Group by design for summary
    const summaryByDesign: Record<string, number> = {};
    outpassItems.forEach((item: any) => {
      summaryByDesign[item.design] = (summaryByDesign[item.design] || 0) + 1;
    });

    return NextResponse.json({
      success: true,
      count: outpassItems.length,
      summaryByDesign,
      items: itemsWithOutpassInfo,
    });
  } catch (error: any) {
    console.error("Error fetching outpass items:", error);
    return NextResponse.json(
      { success: false, message: error.message || "Failed to fetch outpass items" },
      { status: 500 }
    );
  }
}
