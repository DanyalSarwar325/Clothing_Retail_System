import { NextRequest, NextResponse } from "next/server";
import prisma from "@/app/libs/prisma";

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { barcodeData, department, scannedBy } = body;

    if (!barcodeData) {
      return NextResponse.json(
        { success: false, message: "Barcode data is required" },
        { status: 400 }
      );
    }

    if (!department) {
      return NextResponse.json(
        { success: false, message: "Department is required" },
        { status: 400 }
      );
    }

    if (department === "Store") {
      return NextResponse.json(
        { success: false, message: "Store department cannot generate outpass" },
        { status: 403 }
      );
    }

    if (!scannedBy) {
      return NextResponse.json(
        { success: false, message: "Worker name is required" },
        { status: 400 }
      );
    }

    try {
      JSON.parse(barcodeData);
    } catch {
      return NextResponse.json(
        { success: false, message: "Invalid barcode format" },
        { status: 400 }
      );
    }

    const barcode = await prisma.barcode.findUnique({
      where: { barcodeData },
      include: {
        departmentHistory: { orderBy: { scannedAt: "asc" } },
      },
    });

    if (!barcode) {
      return NextResponse.json(
        { success: false, message: "Barcode not found" },
        { status: 404 }
      );
    }

    if (barcode.currentDepartment === "Outpass") {
      return NextResponse.json(
        { success: false, message: "This item is already on Outpass", alreadyOnOutpass: true },
        { status: 400 }
      );
    }

    if (barcode.status === "defective" || barcode.status === "damaged") {
      return NextResponse.json(
        { success: false, message: "Cannot generate outpass for defective/damaged items" },
        { status: 400 }
      );
    }

    const updatedBarcode = await prisma.barcode.update({
      where: { id: barcode.id },
      data: {
        currentDepartment: "Outpass",
        scannedAt: new Date(),
        departmentHistory: {
          create: {
            department: "Outpass",
            scannedAt: new Date(),
            scannedBy,
          },
        },
      },
      include: {
        departmentHistory: { orderBy: { scannedAt: "asc" } },
      },
    });

    return NextResponse.json({
      success: true,
      message: `Outpass generated by ${scannedBy} from ${department}`,
      barcode: {
        id: updatedBarcode.id,
        _id: updatedBarcode.id,
        design: updatedBarcode.design,
        size: updatedBarcode.size,
        suitType: updatedBarcode.suitType,
        item: updatedBarcode.item,
        unitNumber: updatedBarcode.unitNumber,
        status: updatedBarcode.status,
        currentDepartment: updatedBarcode.currentDepartment,
        departmentHistory: updatedBarcode.departmentHistory.map((h) => ({
          _id: h.id,
          department: h.department,
          scannedAt: h.scannedAt,
          scannedBy: h.scannedBy,
        })),
      },
    });
  } catch (error: any) {
    console.error("Outpass error:", error);
    return NextResponse.json(
      { success: false, message: error.message || "Failed to generate outpass" },
      { status: 500 }
    );
  }
}

export async function GET(request: NextRequest) {
  try {
    const { searchParams } = new URL(request.url);
    const design = searchParams.get("design");

    const where: any = {
      currentDepartment: "Outpass",
      status: { notIn: ["defective", "damaged"] },
    };

    if (design) {
      where.design = { contains: design, mode: "insensitive" };
    }

    const outpassItems = await prisma.barcode.findMany({
      where,
      include: {
        departmentHistory: { orderBy: { scannedAt: "asc" } },
      },
      orderBy: { scannedAt: "desc" },
    });

    const itemsWithOutpassInfo = outpassItems.map((item) => {
      const history = item.departmentHistory;
      const lastScan = history[history.length - 1];
      const previousDept = history.length > 1 ? history[history.length - 2] : null;

      return {
        id: item.id,
        _id: item.id,
        design: item.design,
        size: item.size,
        suitType: item.suitType,
        item: item.item,
        unitNumber: item.unitNumber,
        status: item.status,
        outpassInfo: {
          generatedAt: lastScan?.scannedAt,
          generatedBy: lastScan?.scannedBy,
          fromDepartment: previousDept?.department || "Unknown",
        },
        departmentHistory: history.map((h) => ({
          _id: h.id,
          department: h.department,
          scannedAt: h.scannedAt,
          scannedBy: h.scannedBy,
        })),
      };
    });

    const summaryByDesign: Record<string, number> = {};
    outpassItems.forEach((item) => {
      summaryByDesign[item.design] = (summaryByDesign[item.design] || 0) + 1;
    });

    return NextResponse.json({
      success: true,
      count: outpassItems.length,
      summaryByDesign,
      items: itemsWithOutpassInfo,
    });
  } catch (error: any) {
    console.error("Error fetching outpass items:", error);
    return NextResponse.json(
      { success: false, message: error.message || "Failed to fetch outpass items" },
      { status: 500 }
    );
  }
}
